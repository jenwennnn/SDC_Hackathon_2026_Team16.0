# Exposure creeps up a little each month (AI keeps improving).
EXPOSURE_STEP_PER_MONTH = 0.03


def clamp(value, low, high):
    return max(low, min(high, value))


def build_signal(task_type, base, months_before_latest):
    """Build one signal row for a given batch (0 = newest, 1 = one month older...)."""
    k = months_before_latest
    return {
        "task_type": task_type,
        "demand_index": round(clamp(base["demand_index"] - base["drift"] * k, -1.0, 1.0), 2),
        "exposure_steady": round(clamp(base["exposure_steady"] - EXPOSURE_STEP_PER_MONTH * k, 0.0, 1.0), 2),
        "exposure_rapid": round(clamp(base["exposure_rapid"] - EXPOSURE_STEP_PER_MONTH * k, 0.0, 1.0), 2),
        "augment_index": base["augment_index"],
        "confidence": base["confidence"],
        "reason_en": base["reason_en"],
    }


def build_dataset():
    batches = []
    last = len(BATCHES) - 1
    for i, b in enumerate(BATCHES):
        months_before_latest = last - i
        batches.append({
            "meta": {
                "batch_id": b["batch_id"],
                "data_date": b["data_date"],
                "source_name": SOURCE_NAME,
                "source_note": SOURCE_NOTE,
                "is_synthetic": True,
            },
            "signals": [
                build_signal(tt, base, months_before_latest)
                for tt, base in BASE.items()
            ],
        })
    return {
        "schema_version": "0.1",
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "batches": batches,
    }


def main():
    dataset = build_dataset()
    os.makedirs(os.path.dirname(OUTPUT_PATH), exist_ok=True)
    with open(OUTPUT_PATH, "w", encoding="utf-8") as f:
        json.dump(dataset, f, indent=2, ensure_ascii=True)
    print(f"Wrote {OUTPUT_PATH}: {len(dataset['batches'])} batches, "
          f"{len(BASE)} task types each.")


if __name__ == "__main__":
    main()